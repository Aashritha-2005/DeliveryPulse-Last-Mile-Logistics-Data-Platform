"""Profile a generated dataset and write ``docs/data_quality_report.md`` from its manifest.

Usage (from the project root)::

    uv run python -m src.groundtruth.profile --orders 50000 --seed 42

The manifest is verified against the raw files first (see ``verify.py``); nothing is written if
any check fails. Every number in the report comes from the manifest and the files.
"""

import argparse
import logging
import sys
from collections import Counter
from collections.abc import Sequence
from pathlib import Path

from src.groundtruth.manifest import (
    ACCEPTED,
    DISPOSITIONS,
    MANIFEST_FILE_NAME,
    PENDING,
    Case,
    Manifest,
    load_manifest,
)
from src.groundtruth.report_sections import keep_section
from src.groundtruth.verify import (
    PER_CASE_ONLY_TYPES,
    SOURCES,
    LoadedBatch,
    expected_reconciliation,
    load_dataset,
    verify,
)
from src.ingestion.generator_config import (
    DERIVED_CASE_TYPES,
    INJECTED_DEFECT_TYPES,
    NATURAL_CASE_TYPES,
    REPORTING_TIMEZONE,
    SOURCE_FILES,
    GenerationError,
    add_config_arguments,
    config_from_args,
)
from src.utils.logging import configure_logging

logger = logging.getLogger("deliverypulse.profile")

DEFAULT_REPORT = Path("docs/data_quality_report.md")
SUMMARY_LABELS = (
    ("orders_total", "Orders simulated"),
    ("orders_delivered", "Orders delivered"),
    ("orders_cancelled_customer", "Orders cancelled by the customer"),
    ("orders_cancelled_no_driver", "Orders cancelled because no driver was free"),
    ("orders_final_state_after_last_cutoff", "Orders still open at the last cutoff"),
    ("drivers_total", "Drivers"),
    ("drivers_idle", "Drivers who never work (invalid driver rows)"),
    ("drivers_delayed", "Drivers whose row arrives one batch late"),
    ("delivery_events_simulated", "Delivery events simulated (before defects)"),
    ("shift_events_simulated", "Shift events simulated (before defects)"),
)
ORDER_SHARE_KEYS = (
    "orders_delivered",
    "orders_cancelled_customer",
    "orders_cancelled_no_driver",
    "orders_final_state_after_last_cutoff",
)


def _percent(part: int, whole: int) -> str:
    return "n/a" if whole == 0 else f"{100 * part / whole:.2f}%"


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def _kind(defect_type: str) -> str:
    if defect_type in NATURAL_CASE_TYPES:
        return "natural"
    if defect_type in DERIVED_CASE_TYPES:
        return "derived"
    return "injected"


def _type_rows(cases: tuple[Case, ...], batches: int) -> list[list[str]]:
    by_type: dict[str, list[Case]] = {}
    for case in cases:
        by_type.setdefault(case.defect_type, []).append(case)
    rows: list[list[str]] = []
    ordered = (*INJECTED_DEFECT_TYPES, *DERIVED_CASE_TYPES, *NATURAL_CASE_TYPES)
    for defect_type in ordered:
        group = by_type.get(defect_type, [])
        if not group:
            rows.append([f"`{defect_type}`", "", "", "", *["0"] * batches, "0", ""])
            continue
        per_batch = Counter(case.batch for case in group)
        reasons = sorted({case.reason for case in group if case.reason})
        rows.append(
            [
                f"`{defect_type}`",
                group[0].source,
                group[0].expected_disposition,
                ", ".join(f"`{reason}`" for reason in reasons),
                *[str(per_batch[b]) for b in range(1, batches + 1)],
                str(len(group)),
                _kind(defect_type),
            ]
        )
    return rows


def build_report(manifest: Manifest, batches: list[LoadedBatch]) -> str:
    """Render the Markdown report (deterministic: no dates or runtimes)."""
    n = len(batches)
    batch_headers = [f"batch-{batch.sequence}" for batch in batches]
    lines = [
        "# Data quality report",
        "",
        "> Generated by `make profile` from the defect manifest and the raw files.",
        "> Do not edit by hand; regenerate it after `make generate`.",
        "",
        "## Dataset",
        "",
        *_table(
            ["Item", "Value"],
            [
                ["Dataset", f"`{manifest.dataset}`"],
                ["Config sha256", f"`{manifest.config_sha256}`"],
                ["Reporting timezone", REPORTING_TIMEZONE],
                ["Batches", str(n)],
            ],
        ),
        "",
        *_table(
            ["Batch", "Window start (UTC)", "Window end, exclusive (UTC)", "batch_id"],
            [
                [
                    f"batch-{batch.sequence}",
                    str(batch.metadata["window_start"]),
                    str(batch.metadata["window_end_exclusive"]),
                    f"`{batch.metadata['batch_id']}`",
                ]
                for batch in batches
            ],
        ),
        "",
        "## Rows per file",
        "",
    ]
    file_rows = []
    for source, name in SOURCE_FILES:
        counts = [len(batch.rows[source]) for batch in batches]
        file_rows.append([f"`{name}`", *[str(count) for count in counts], str(sum(counts))])
    lines += _table(["File", *batch_headers, "Total"], file_rows)

    summary = manifest.simulation_summary
    total_orders = summary.get("orders_total", 0)
    summary_rows = [
        [
            label,
            str(summary.get(key, 0)),
            _percent(summary.get(key, 0), total_orders) if key in ORDER_SHARE_KEYS else "",
        ]
        for key, label in SUMMARY_LABELS
    ]
    lines += [
        "",
        "## Simulation summary (ground truth)",
        "",
        "Shares are of all simulated orders. Cancellations are split by cause.",
        "",
        *_table(["Measure", "Count", "Share of orders"], summary_rows),
        "",
        "## Defects and expected dispositions",
        "",
        "Injected: deliberately added. Derived: every record of a delayed parent. "
        "Natural: genuine later versions of orders in progress at a cutoff.",
        "",
        *_table(
            ["Type", "Source", "Expected disposition", "Reason", *batch_headers, "Total", "Kind"],
            _type_rows(manifest.cases, n),
        ),
        "",
        "## Expected reconciliation per source and batch",
        "",
        "input = accepted + rejected + duplicate + stale_ignored + pending, per source.",
        "",
    ]
    reconciliation = expected_reconciliation(batches, manifest.cases)
    recon_rows = []
    for source in SOURCES:
        for batch in batches:
            expected = reconciliation[(source, batch.sequence)]
            parts = [expected[d] for d in DISPOSITIONS]
            balanced = (
                "yes" if sum(parts) == expected["input"] and expected[ACCEPTED] >= 0 else "NO"
            )
            label = f"batch-{batch.sequence}"
            recon_rows.append([source, label, str(expected["input"]), *map(str, parts), balanced])
    lines += _table(["Source", "Batch", "Input", *DISPOSITIONS, "Balanced"], recon_rows)

    pending = Counter(
        (case.source, case.batch) for case in manifest.cases if case.expected_disposition == PENDING
    )
    pending_rows = [
        [source, f"batch-{batch}", f"batch-{batch + 1}", str(count)]
        for (source, batch), count in sorted(pending.items())
    ]
    lines += [
        "",
        "## Pending records and where their parent arrives",
        "",
        *_table(["Source", "Pending in", "Parent arrives in", "Records"], pending_rows),
        "",
        "## Verification",
        "",
        f"- Every one of the {len(manifest.cases)} manifest cases was checked against the files.",
        "- Case counts per type equal counts derived from the files alone, except "
        + ", ".join(f"`{t}`" for t in PER_CASE_ONLY_TYPES)
        + ", which are verified per case only.",
        "- batch_ids were recomputed from the data files and the config.",
        "- No two scenarios share a record, an order or a driver.",
        "",
    ]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    """Command-line entry point; returns the process exit code."""
    parser = argparse.ArgumentParser(description="Profile a generated dataset.")
    add_config_arguments(parser)
    parser.add_argument("--report", type=Path, default=DEFAULT_REPORT)
    args = parser.parse_args(argv)
    configure_logging()
    try:
        config = config_from_args(args)
    except GenerationError as exc:
        logger.error("%s", exc)
        return 1
    raw_dir: Path = args.raw_dir
    ground_truth_dir: Path = args.ground_truth_dir
    report_path: Path = args.report
    dataset_dir = raw_dir / config.dataset_name()
    manifest_path = ground_truth_dir / config.dataset_name() / MANIFEST_FILE_NAME
    if not dataset_dir.is_dir() or not manifest_path.is_file():
        logger.error("Dataset %s not found; run `make generate` first.", config.dataset_name())
        return 1
    manifest = load_manifest(manifest_path)
    problems = verify(dataset_dir, manifest)
    if problems:
        for problem in problems[:50]:
            logger.error("verification failed: %s", problem)
        logger.error("%d problems; report not written.", len(problems))
        return 1
    report = build_report(manifest, load_dataset(dataset_dir))
    if report_path.is_file():
        # The quality section belongs to `make quality-report`; keep it.
        report = keep_section(report, report_path.read_text(encoding="utf-8"))
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(report, encoding="utf-8", newline="\n")
    sys.stdout.write(report)
    logger.info("verified %d cases; report written to %s", len(manifest.cases), report_path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
