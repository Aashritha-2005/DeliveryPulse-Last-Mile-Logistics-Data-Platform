class GenerationError(RuntimeError):
    """The generator cannot produce the requested dataset (for example, too few orders)."""


def default_driver_count(orders: int) -> int:
    """Default number of drivers for ``orders`` orders (configurable with ``--drivers``)."""
    return max(20, orders // 60)


@dataclass(frozen=True)
class GeneratorConfig:
    """Every setting that influences the generated bytes."""

    seed: int
    n_orders: int
    n_drivers: int
    generator_version: int = GENERATOR_VERSION
    reference_ts: str = DEFAULT_REFERENCE_TS
    n_batches: int = 3
    days_per_batch: int = 7
    gps_ping_interval_seconds: int = 240
    city_radius_km: float = 12.0
    customer_cancel_rate: float = 0.04
    defect_rates_per_10k: tuple[tuple[str, float], ...] = DEFAULT_DEFECT_RATES_PER_10K

    @classmethod
    def create(cls, *, orders: int, seed: int, drivers: int | None = None) -> Self:
        """Validate the user-facing settings and build a config with all other defaults."""
        if orders < MIN_ORDERS:
            raise GenerationError(f"--orders must be at least {MIN_ORDERS}, got {orders}.")
        if seed < 0:
            raise GenerationError(f"--seed must be non-negative, got {seed}.")
        resolved_drivers = default_driver_count(orders) if drivers is None else drivers
        if resolved_drivers < MIN_DRIVERS:
            raise GenerationError(f"--drivers must be at least {MIN_DRIVERS}, got {drivers}.")
        return cls(seed=seed, n_orders=orders, n_drivers=resolved_drivers)

    def canonical_json(self) -> str:
        """Canonical JSON: sorted keys, no whitespace, ASCII only."""
        return json.dumps(asdict(self), sort_keys=True, separators=(",", ":"), ensure_ascii=True)

    def sha256(self) -> str:
        """SHA-256 hex digest of :meth:`canonical_json`."""
        return hashlib.sha256(self.canonical_json().encode("utf-8")).hexdigest()

    def dataset_name(self) -> str:
        """Folder name of the dataset: seed, size and a short config hash."""
        return f"seed-{self.seed}_orders-{self.n_orders}_cfg-{self.sha256()[:8]}"

    def reference_epoch(self) -> int:
        """The fixed reference timestamp (end of the last batch window) as epoch seconds."""
        epoch = parse_utc(self.reference_ts)
        if epoch is None:
            raise GenerationError(f"Invalid reference_ts {self.reference_ts!r}.")
        return epoch

    def window_start_epoch(self) -> int:
        """Start of the first batch window."""
        total_days = self.n_batches * self.days_per_batch
        return self.reference_epoch() - total_days * SECONDS_PER_DAY

    def cutoffs(self) -> tuple[int, ...]:
        """Exclusive end of each batch window, oldest first (the last equals the reference)."""
        start = self.window_start_epoch()
        window_seconds = self.days_per_batch * SECONDS_PER_DAY
        return tuple(start + k * window_seconds for k in range(1, self.n_batches + 1))

    def defect_count(self, defect_type: str) -> int:
        """Number of cases to inject for ``defect_type``."""
        rate = dict(self.defect_rates_per_10k)[defect_type]
        return max(1, round(rate * self.n_orders / 10_000))


def add_config_arguments(parser: argparse.ArgumentParser) -> None:
    """Add the dataset-selecting CLI arguments shared by the generator and the profiler."""
    parser.add_argument("--orders", type=int, default=DEFAULT_ORDERS, help="number of orders")
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED, help="random seed")
    parser.add_argument(
        "--drivers",
        type=int,
        default=None,
        help="number of drivers (default: max(20, orders // 60))",
    )
    parser.add_argument("--raw-dir", type=Path, default=DEFAULT_RAW_DIR)
    parser.add_argument("--ground-truth-dir", type=Path, default=DEFAULT_GROUND_TRUTH_DIR)


def config_from_args(args: argparse.Namespace) -> GeneratorConfig:
    """Build a :class:`GeneratorConfig` from parsed CLI arguments."""
    orders: int = args.orders
    seed: int = args.seed
    drivers: int | None = args.drivers
    return GeneratorConfig.create(orders=orders, seed=seed, drivers=drivers)
